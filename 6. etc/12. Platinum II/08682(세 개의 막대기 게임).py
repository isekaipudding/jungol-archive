import sys

input = sys.stdin.readline

# 이 문제는 스프라그-그런디 정리 문제입니다.
# 초기 상태가 a * 2^x, b * 2^y, c * 2^z(a, b, c는 홀수)라고 가정합니다.
# 이 때 x = y = z인 상태를 먼저 깨부수는 플레이어가 패배하게 됩니다.
# 왜냐면 무조건 필패할 수 밖에 없는 경우 [1, 1, 1]에서 보면 x = y = z = 0이 되며
# 그 다음 x = y = z가 아닐 때 턴을 받은 플레이어는 x = y = z로 강제로 만들 수 있는 방법이 존재하므로
# 상대방은 무조건 x = y = z를 부술 밖에 없는 가불기에 걸립니다.
# 그러다 [1, 1, 1] 상태에 걸리게 되어 결국 x = y = z를 먼저 부순 쪽이 패배할 수 밖에 없습니다.

# 즉, 초기 상태가 x = y = z인 경우 선공이 강제로 부수게 되어 후공이 이기게 되고
# 반대로 초기 상태가 x = y = z가 아닌 경우 선공이 강제로 x = y = z로 만들어서
# 후공이 강제로 x = y = z를 부수게 만들어서 선공이 승리하게 됩니다.

# 참고로 강제로 x = y = z로 만드는 방법은
# 임의의 수를 하나 제거하고 그 다음 지수 m을 설정합니다.
# 이 때 x = y = z가 아닌 경우 무조건 짝수 1개 존재하므로
# 그 짝수를 1 * 2^m, (홀수) * 2^m으로 분리하게 만들어서 모든 막대가 a * 2^m 형식으로 만들 수 있습니다.

T:int = int(input().rstrip())

for _ in range(T):
    A, B, C = map(int, input().split())
    
    a, b, c = 0, 0, 0
    
    while not A & 1:
        A >>= 1
        a += 1
    while not B & 1:
        B >>= 1
        b += 1
    while not C & 1:
        C >>= 1
        c += 1
    
    if a == b == c:
        print("H")
    else:
        print("J")